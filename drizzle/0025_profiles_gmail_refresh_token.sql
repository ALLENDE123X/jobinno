-- profiles.gmail_refresh_token (JOB-189): the encrypted refresh token behind
-- a connected Gmail account. It exists so automated account creation on ATS
-- platforms that gate signup behind an emailed verification code (see
-- lib/future-gmail/README.md) has something to read from once that flow is
-- wired up; nothing reads it yet.
--
-- The value stored here is never the raw refresh token. It is the output of
-- lib/gmail-token-crypto.ts's encryptGmailRefreshToken, AES-256-GCM under a
-- key that lives only in GMAIL_TOKEN_ENCRYPTION_KEY and never in this
-- database, so a stolen row is useless without a stolen environment to go
-- with it.
--
-- The grant this column needs is `0026_profiles_gmail_refresh_token_privileges.sql`,
-- a separate file for the same reason `github_url` (0015) and its grant (0016)
-- are two files rather than one: `drizzle-kit push`, which CI uses to build
-- its throwaway database, applies a plain ALTER TABLE like this one on its
-- own by diffing lib/db/schema.ts, but cannot see a GRANT at all because the
-- Drizzle schema DSL has no way to express one. Keeping the two apart means
-- `.github/workflows/ci.yml` can apply the grant file by explicit name
-- without also re-running an ALTER TABLE that `push` already handled, which
-- would fail on "column already exists".
--
-- ── Not generated by a clean `drizzle-kit generate` ─────────────────────────
-- Running it for this column also tried to recreate `creators` and re-add a
-- dozen already-live columns on `applications` and `profiles`. The local
-- snapshot history it was diffing against (`drizzle/meta/0020_snapshot.json`)
-- is missing everything several hand-written migrations since added directly
-- as SQL rather than through `drizzle-kit generate` — `creators` included —
-- so drizzle-kit's idea of "the current state" was years out of date and its
-- diff was mostly noise. This file keeps only the one real statement; the
-- snapshot `generate` produced alongside it is accurate as of this column
-- and should make the next `drizzle-kit generate` a clean diff again.
ALTER TABLE "profiles" ADD COLUMN "gmail_refresh_token" text;
